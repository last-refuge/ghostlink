// ISO-8859-12 was never assigned; it is intentionally absent.
pub fn validate(name: &str) -> Result<()> {
    if NAMES.contains(&name) {
        Ok(())
    } else {
        bail!("Unsupported character set: {name}")
    }
}
pub struct Codec {
    kind: Kind,
}
enum Kind {
    Utf8,
    Iso(&'static [u32; 128]),
    Other {
        encoding: &'static encoding_rs::Encoding,
        decoder: encoding_rs::Decoder,
    },
}
impl Codec {
    pub fn new(name: &str) -> Result<Self> {
        validate(name)?;
        let kind = if name == "UTF-8" {
            Kind::Utf8
        } else if let Some(index) = name.strip_prefix("ISO-8859-") {
            Kind::Iso(iso_table(index.parse()?))
        } else {
            let encoding =
                encoding_rs::Encoding::for_label(name.as_bytes()).expect("listed encoding");
            Kind::Other {
                encoding,
                decoder: encoding.new_decoder_without_bom_handling(),
            }
        };
        Ok(Self { kind })
    }
    pub fn decode<'a>(&mut self, bytes: &'a [u8], last: bool) -> Cow<'a, [u8]> {
        match &mut self.kind {
            Kind::Utf8 => Cow::Borrowed(bytes),
            Kind::Iso(table) => Cow::Owned(
                bytes
                    .iter()
                    .map(|&byte| {
                        if byte < 128 {
                            char::from(byte)
                        } else {
                            char::from_u32(table[usize::from(byte - 128)]).unwrap()
                        }
                    })
                    .collect::<String>()
                    .into_bytes(),
            ),
            Kind::Other { decoder, .. } => {
                let mut text = String::with_capacity(
                    decoder
                        .max_utf8_buffer_length(bytes.len())
                        .expect("bounded SSH packet"),
                );
                let (result, consumed, _) = decoder.decode_to_string(bytes, &mut text, last);
                debug_assert_eq!(result, encoding_rs::CoderResult::InputEmpty);
                debug_assert_eq!(consumed, bytes.len());
                Cow::Owned(text.into_bytes())
            }
        }
    }
    /// Preserve owned UTF-8 buffers without allocating a second copy.
    pub fn encode_owned(&self, bytes: Vec<u8>) -> Vec<u8> {
        if matches!(self.kind, Kind::Utf8) {
            bytes
        } else {
            self.encode(&bytes).into_owned()
        }
    }
    pub fn encode<'a>(&self, bytes: &'a [u8]) -> Cow<'a, [u8]> {
        if matches!(self.kind, Kind::Utf8) {
            return Cow::Borrowed(bytes);
        }
        // Raw protocol bytes (e.g. legacy mouse reports) are not Unicode text.
        let Ok(text) = std::str::from_utf8(bytes) else {
            return Cow::Borrowed(bytes);
        };
        match &self.kind {
            Kind::Utf8 => Cow::Borrowed(bytes),
            Kind::Iso(table) => Cow::Owned(
                text.chars()
                    .map(|ch| {
                        if (ch as u32) < 128 {
                            ch as u8
                        } else {
                            table
                                .iter()
                                .position(|&value| value == ch as u32 && value != 0xfffd)
                                .map_or(b'?', |index| index as u8 + 128)
                        }
                    })
                    .collect(),
            ),
            Kind::Other { encoding, .. } => {
                // Terminal input uses '?' for unrepresentable characters, never HTML entities.
                let mut encoder = encoding.new_encoder();
                let mut output = Vec::new();
                let mut rest = text;
                loop {
                    output.reserve(rest.len().saturating_mul(4) + 16);
                    let (result, read) = encoder.encode_from_utf8_to_vec_without_replacement(
                        rest,
                        &mut output,
                        true,
                    );
                    rest = &rest[read..];
                    match result {
                        encoding_rs::EncoderResult::InputEmpty => break,
                        encoding_rs::EncoderResult::OutputFull => continue,
                        encoding_rs::EncoderResult::Unmappable(_) => output.push(b'?'),
                    }
                }
                Cow::Owned(output)
            }
        }
    }
}

