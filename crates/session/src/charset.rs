#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn multibyte_packets_round_trip_without_losing_pending_characters() {
        for (name, text) in [
            ("Shift_JIS", "日本語"),
            ("EUC-JP", "日本語"),
            ("EUC-KR", "한국어"),
            ("GB18030", "中文😀"),
            ("Big5", "中文"),
        ] {
            let mut codec = Codec::new(name).unwrap();
            let encoded = codec.encode(text.as_bytes()).into_owned();
            let mut decoded = Vec::new();
            for byte in &encoded {
                decoded.extend_from_slice(&codec.decode(&[*byte], false));
            }
            decoded.extend_from_slice(&codec.decode(&[], true));
            assert_eq!(decoded, text.as_bytes(), "{name}");
        }
    }
    #[test]
    fn iso_encodings_are_exact_and_all_advertised_encodings_work() {
        for name in NAMES {
            let mut codec = Codec::new(name).unwrap();
            assert_eq!(codec.encode(b"hello\x1b[31m"), &b"hello\x1b[31m"[..]);
            assert_eq!(codec.decode(b"hello\x1b[31m", true), &b"hello\x1b[31m"[..]);
        }
        for number in (1..=15).filter(|&n| n != 12) {
            let mut codec = Codec::new(&format!("ISO-8859-{number}")).unwrap();
            for byte in 128..=255 {
                let decoded = codec.decode(&[byte], false).into_owned();
                if decoded != "�".as_bytes() {
                    assert_eq!(codec.encode(&decoded), vec![byte]);
                }
            }
        }
        let mut latin1 = Codec::new("ISO-8859-1").unwrap();
        assert_eq!(latin1.decode(&[0x80], false), "\u{80}".as_bytes());
        assert_eq!(latin1.encode("€".as_bytes()), &b"?"[..]);
        assert!(Codec::new("ISO-8859-12").is_err());
        assert!(Codec::new("UTF-16").is_err());
        assert!(matches!(
            Codec::new("UTF-8").unwrap().decode(b"abc", false),
            Cow::Borrowed(_)
        ));
    }
    #[test]
    fn invalid_and_truncated_sequences_replace_and_unmappable_input_is_plain_text() {
        let mut codec = Codec::new("Shift_JIS").unwrap();
        assert!(codec.decode(&[0x82], false).is_empty());
        assert_eq!(codec.decode(&[], true), "�".as_bytes());
        assert_eq!(codec.encode("abc😀def".as_bytes()), &b"abc?def"[..]);
    }
}

